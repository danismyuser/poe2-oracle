// Generate src/lib/affix-data.ts from CoE's authoritative data
// (already extracted into src/lib/coe-lookup.ts + src/lib/mod-weights.ts).
//
// Produces:
//  - ITEM_CLASSES: every PoE2 base CATEGORY from CoE (76 total).
//    Body Armour, Helmet, Gloves, Boots, Shield are split by attribute
//    requirement (DEX, DEX/INT, INT, STR, STR/DEX, STR/INT) because mod
//    pools differ between them (INT armour rolls Energy Shield, STR rolls
//    Armour, DEX rolls Evasion, etc.) — this matches what CoE / the game
//    actually does.
//  - BASES: per-category list of specific named items ("Sacramental Robe",
//    "Crude Bow", etc.) from COE_BITEMS.
//  - MODS: per-category prefix/suffix pools from COE_BASE_MODS, with tier
//    names from the Google Sheet's MOD_DATA where available.
//
// Re-run whenever upstream PoE2 data changes:
//   node scripts/build-affix-data.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

function extractConst(src, name) {
  // Matches both `Record<...> = {...}` and `Record<...> = {...}` followed by
  // any export/function/comment/interface/EOF.
  const re = new RegExp(`export const ${name}[^=]*=\\s*(\\{[\\s\\S]*?\\});\\s*(?:export|function|/\\*\\*|interface|const|$)`, "m");
  const m = src.match(re);
  return m ? JSON.parse(m[1]) : null;
}

const lookupTs = fs.readFileSync(path.join(root, "src/lib/coe-lookup.ts"), "utf-8");
const weightsTs = fs.readFileSync(path.join(root, "src/lib/mod-weights.ts"), "utf-8");

const COE_BITEMS = extractConst(lookupTs, "COE_BITEMS");
const COE_BASE_MODS = extractConst(lookupTs, "COE_BASE_MODS");
const MOD_DATA = extractConst(weightsTs, "MOD_DATA");

if (!COE_BITEMS || !COE_BASE_MODS || !MOD_DATA) {
  console.error("Failed to extract one of COE_BITEMS / COE_BASE_MODS / MOD_DATA — make sure build-coe-lookup.mjs and build-mod-weights.mjs have been run.");
  process.exit(1);
}

// ── ITEM_CLASSES (alphabetical) ───────────────────────────────────────────
// We only include categories that have at least one prefix or suffix in
// COE_BASE_MODS — purely cosmetic categories with no rollable mods (e.g.
// Precursor Tablet variants) get filtered out so the dropdown stays useful.
const allCategories = Object.keys(COE_BASE_MODS).filter((cat) => {
  const pool = COE_BASE_MODS[cat];
  return (pool?.prefixes?.length ?? 0) + (pool?.suffixes?.length ?? 0) > 0;
}).sort();

// ── BASES per category ────────────────────────────────────────────────────
const basesByCategory = {};
for (const [bitemName, info] of Object.entries(COE_BITEMS)) {
  const cat = info.bn;
  if (!cat) continue;
  if (!allCategories.includes(cat)) continue;
  basesByCategory[cat] ??= [];
  basesByCategory[cat].push(bitemName);
}
for (const cat in basesByCategory) basesByCategory[cat].sort();

// Categories with no bitems either get an empty array (shouldn't happen in
// practice, but defensive) or the category name itself as a single entry.
for (const cat of allCategories) {
  if (!basesByCategory[cat] || basesByCategory[cat].length === 0) {
    basesByCategory[cat] = [cat];
  }
}

// ── MODS per category, with tier info ─────────────────────────────────────
// Tier names come from the Google Sheet's MOD_DATA — keyed by UPPERCASE
// category name (e.g. "BOW", "BODY ARMOUR (INT)"). When the sheet doesn't
// have data for a particular mod we fall back to generic ["T1","T2",...]
// based on a heuristic count.
function getTierNames(category, type, modName) {
  const sheetKey = category.toUpperCase();
  const entry = MOD_DATA[sheetKey]?.[type]?.[modName];
  if (entry?.tiers) {
    const names = entry.tiers
      .map((t, i) => t?.tierName || `T${i + 1}`)
      .filter(Boolean);
    if (names.length > 0) return names;
  }
  // Default: 5 generic tiers
  return ["T1", "T2", "T3", "T4", "T5"];
}

const modsByCategory = {};
for (const cat of allCategories) {
  const pool = COE_BASE_MODS[cat];
  modsByCategory[cat] = {
    prefixes: pool.prefixes.map((name) => ({ name, tiers: getTierNames(cat, "PREFIX", name) })),
    suffixes: pool.suffixes.map((name) => ({ name, tiers: getTierNames(cat, "SUFFIX", name) })),
  };
}

// ── Write the file ────────────────────────────────────────────────────────
const out = `// AUTO-GENERATED by scripts/build-affix-data.mjs — do not edit by hand.
// Source: Craft of Exile's poec_data.json (basemods + bitems tables) +
// the community PoE2 mod-weights spreadsheet for tier names.
// Generated: ${new Date().toISOString()}
//
// ITEM_CLASSES: ${allCategories.length} categories. Armour types (Helmet,
// Body Armour, Gloves, Boots, Shield) are split by attribute requirement
// (DEX / DEX-INT / INT / STR / STR-DEX / STR-INT) because their mod pools
// differ — INT armour rolls Energy Shield, STR rolls Armour, etc.

export interface AffixDef {
  name: string;
  tiers: string[];
}

export interface ModPool {
  prefixes: AffixDef[];
  suffixes: AffixDef[];
}

export const ITEM_CLASSES = ${JSON.stringify(allCategories, null, 2)} as const;

export type ItemClass = (typeof ITEM_CLASSES)[number];

/** Specific base items per category. Sourced from CoE's bitems table. */
export const BASES: Record<ItemClass, string[]> = ${JSON.stringify(basesByCategory, null, 2)};

/** Per-category mod pool (prefixes + suffixes with tier names).
 *  Mod NAMES from CoE's basemods table (authoritative — what CoE's
 *  emulator displays). Tier NAMES from the community sheet. */
export const MODS: Record<ItemClass, ModPool> = ${JSON.stringify(modsByCategory, null, 2)};

/** Look up the mod pool for an item class. Returns empty pools if the class
 *  has no entry (defensive — shouldn't happen in practice). */
export function getModPool(itemClass: ItemClass | string): ModPool {
  return MODS[itemClass as ItemClass] ?? { prefixes: [], suffixes: [] };
}
`;

fs.writeFileSync(path.join(root, "src/lib/affix-data.ts"), out, "utf-8");
console.log(`Wrote src/lib/affix-data.ts`);
console.log(`  ${allCategories.length} item classes`);
const totalBases = Object.values(basesByCategory).reduce((n, a) => n + a.length, 0);
const totalMods = Object.values(modsByCategory).reduce((n, m) => n + m.prefixes.length + m.suffixes.length, 0);
console.log(`  ${totalBases} specific bases`);
console.log(`  ${totalMods} mod entries`);

// Show the armour split to confirm
const armourSplit = allCategories.filter((c) => /^(Body Armour|Helmet|Gloves|Boots|Shield)\b/.test(c));
console.log(`\nArmour categories (${armourSplit.length}):`);
for (const c of armourSplit) console.log(`  ${c}  (${basesByCategory[c]?.length ?? 0} bases, ${modsByCategory[c].prefixes.length} prefix + ${modsByCategory[c].suffixes.length} suffix)`);
