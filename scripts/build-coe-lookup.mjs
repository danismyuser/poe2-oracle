// Build-time generator for src/lib/coe-lookup.ts
// Fetches Craft of Exile's public PoE2 data file and extracts the minimal
// lookups we need to deep-link into their emulator (?game=poe2&b=...&bi=...&lv=...&m=...&e=...&req=...).
//
// Re-run when PoE2 patches add new bases, essences, or modifiers:
//   node scripts/build-coe-lookup.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "..");
const cacheFile = path.join(projectRoot, ".coe-data-cache.json");
const outFile = path.join(projectRoot, "src/lib/coe-lookup.ts");

const DATA_URL = "https://www.craftofexile.com/json/poe2/main/poec_data.json";

async function getRawData() {
  if (fs.existsSync(cacheFile)) {
    const ageMs = Date.now() - fs.statSync(cacheFile).mtimeMs;
    if (ageMs < 24 * 60 * 60 * 1000) {
      console.log("Using cached .coe-data-cache.json (< 24h old)");
      return fs.readFileSync(cacheFile, "utf-8");
    }
  }
  console.log(`Fetching ${DATA_URL} ...`);
  const res = await fetch(DATA_URL);
  if (!res.ok) throw new Error(`CoE fetch failed: HTTP ${res.status}`);
  const text = await res.text();
  fs.writeFileSync(cacheFile, text, "utf-8");
  console.log(`Cached ${(text.length / 1024 / 1024).toFixed(2)} MB to .coe-data-cache.json`);
  return text;
}

function parse(raw) {
  const json = raw.replace(/^poecd\s*=\s*/, "").replace(/;?\s*$/, "");
  return JSON.parse(json);
}

function tsLiteral(value) {
  return JSON.stringify(value, null, 2);
}

/** Normalize a mod name for fuzzy matching: lowercase, collapse whitespace, strip
 *  punctuation that's frequently inconsistent across sources (% signs, dashes). */
function normalizeModName(name) {
  return name
    .toLowerCase()
    .replace(/[#%+]/g, "")
    .replace(/\s+to\s+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

async function main() {
  const raw = await getRawData();
  const d = parse(raw);

  // --- Bases (item categories: "Bow", "Body Armour (INT)", "Ring") ---
  const basesByName = {};
  const baseIdToName = {}; // id_base → name_base, used by bitemsByName below
  for (const b of d.bases.seq) {
    basesByName[b.name_base] = { b: Number(b.id_base) };
    baseIdToName[b.id_base] = b.name_base;
  }

  // --- Bitems (specific items: "Crude Bow", "Sacramental Robe", "Amber Amulet") ---
  // Includes `bn` = parent category name (e.g. "Body Armour (INT)") so we can
  // join into the Google-sheet mod-weight data which is keyed by category.
  const bitemsByName = {};
  for (const bi of d.bitems.seq) {
    bitemsByName[bi.name_bitem] = {
      b: Number(bi.id_base),
      bi: Number(bi.id_bitem),
      bn: baseIdToName[bi.id_base] ?? null,
    };
  }

  // --- Essences ---
  const essencesByName = {};
  for (const e of d.essences.seq) {
    essencesByName[e.name_essence] = Number(e.id_essence);
    const stripped = e.name_essence.replace(/^Essence of\s+/i, "");
    if (stripped !== e.name_essence) essencesByName[stripped] = Number(e.id_essence);
  }

  // --- Modifiers (mod name → id_modifier, used for &req= URL param) ---
  // Only ONE id_modifier per (name + affix) — tiers are encoded by ilvl, not by id.
  // We key by "PREFIX|name" and "SUFFIX|name" since the same mod text can exist
  // as both prefix and suffix on different items.
  const modIdsByKey = {};
  const modIdsByNormalized = {};
  let prefixCount = 0, suffixCount = 0;
  for (const m of d.modifiers.seq) {
    if (m.affix !== "prefix" && m.affix !== "suffix") continue;
    const key = `${m.affix.toUpperCase()}|${m.name_modifier}`;
    modIdsByKey[key] = Number(m.id_modifier);
    const normKey = `${m.affix.toUpperCase()}|${normalizeModName(m.name_modifier)}`;
    modIdsByNormalized[normKey] = Number(m.id_modifier);
    if (m.affix === "prefix") prefixCount++; else suffixCount++;
  }

  const header = `// AUTO-GENERATED by scripts/build-coe-lookup.mjs — do not edit by hand.
// Source: ${DATA_URL}
// Generated: ${new Date().toISOString()}
// Bases: ${Object.keys(basesByName).length} categories, ${Object.keys(bitemsByName).length} specific items
// Essences: ${d.essences.seq.length}
// Modifiers: ${prefixCount} prefixes + ${suffixCount} suffixes = ${prefixCount + suffixCount} total

/** id_base for a Craft of Exile base CATEGORY (e.g. "Bow" → 20). */
export const COE_BASE_CATEGORIES: Record<string, { b: number }> = ${tsLiteral(basesByName)};

/** Specific items (e.g. "Crude Bow" → { b: 20, bi: 231, bn: "Bow" }).
 *  \`bn\` is the parent category name — used to join into mod-weight data
 *  from the Google Sheet which is keyed by category, not specific item. */
export const COE_BITEMS: Record<string, { b: number; bi: number; bn: string | null }> = ${tsLiteral(bitemsByName)};

/** id_essence for a Craft of Exile essence. Keyed by full name AND by stripped
 *  suffix, so both "Essence of Abrasion" and "Abrasion" resolve. */
export const COE_ESSENCES: Record<string, number> = ${tsLiteral(essencesByName)};

/** id_modifier for the &req= URL parameter. Keyed as "PREFIX|<name>" / "SUFFIX|<name>"
 *  since the same mod text can exist as both on different items.
 *  Only ONE id per (name + affix) — tier is encoded by ilvl in the URL, not the id. */
export const COE_MOD_IDS: Record<string, number> = ${tsLiteral(modIdsByKey)};

/** Normalized (lowercase, stripped punctuation) version of COE_MOD_IDS for
 *  fuzzy matching when the Oracle's mod text doesn't match CoE's exact phrasing. */
export const COE_MOD_IDS_NORMALIZED: Record<string, number> = ${tsLiteral(modIdsByNormalized)};

function normalizeModName(name: string): string {
  return name
    .toLowerCase()
    .replace(/[#%+]/g, "")
    .replace(/\\s+to\\s+/g, " ")
    .replace(/\\s+/g, " ")
    .trim();
}

/** Look up the CoE base IDs for a given base name. Tries specific-item first
 *  (more precise), then category. Returns null if neither matches. */
export function lookupCoeBase(name: string): { b: number; bi?: number; bn?: string | null } | null {
  if (COE_BITEMS[name]) return COE_BITEMS[name];
  if (COE_BASE_CATEGORIES[name]) return COE_BASE_CATEGORIES[name];
  return null;
}

/** Look up CoE essence ID for "Essence of Abrasion" / "Abrasion" / "Greater
 *  Essence of Abrasion" (we strip the tier prefix). */
export function lookupCoeEssence(name: string): number | null {
  if (!name) return null;
  const stripped = name.replace(/^(Greater|Perfect|Lesser|Normal)\\s+/i, "");
  return COE_ESSENCES[stripped] ?? COE_ESSENCES[name] ?? null;
}

/** Look up the CoE id_modifier for a mod, given its affix type and name.
 *  Tries exact match first, then a normalized fallback for fuzzy matching. */
export function lookupCoeModId(affix: "prefix" | "suffix", name: string): number | null {
  if (!name) return null;
  const key = \`\${affix.toUpperCase()}|\${name}\`;
  if (COE_MOD_IDS[key] != null) return COE_MOD_IDS[key];
  const normKey = \`\${affix.toUpperCase()}|\${normalizeModName(name)}\`;
  return COE_MOD_IDS_NORMALIZED[normKey] ?? null;
}
`;

  fs.writeFileSync(outFile, header, "utf-8");
  console.log(`Wrote ${outFile}`);
  console.log(`  ${Object.keys(basesByName).length} base categories`);
  console.log(`  ${Object.keys(bitemsByName).length} specific items (now with bn)`);
  console.log(`  ${Object.keys(essencesByName).length} essence keys`);
  console.log(`  ${prefixCount} prefixes + ${suffixCount} suffixes`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
