// Build-time generator for src/lib/coe-lookup.ts
// Fetches Craft of Exile's public PoE2 data file and extracts the minimal
// lookups we need to deep-link into their emulator (?game=poe2&b=...&bi=...&lv=...&m=...&e=...).
//
// Re-run when PoE2 patches add new bases or essences:
//   node scripts/build-coe-lookup.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "..");
const cacheFile = path.join(projectRoot, ".coe-data-cache.json");
const outFile = path.join(projectRoot, "src/lib/coe-lookup.ts");

const DATA_URL = "https://www.craftofexile.com/json/poe2/main/poec_data.json";

async function getRawData() {
  // Use cache if it's less than 24h old, otherwise refetch
  if (fs.existsSync(cacheFile)) {
    const ageMs = Date.now() - fs.statSync(cacheFile).mtimeMs;
    if (ageMs < 24 * 60 * 60 * 1000) {
      console.log("Using cached .coe-data-cache.json (< 24h old)");
      return fs.readFileSync(cacheFile, "utf-8");
    }
  }
  console.log(`Fetching ${DATA_URL} ...`);
  const res = await fetch(DATA_URL);
  if (!res.ok) throw new Error(`CoE fetch failed: HTTP ${res.status}`);
  const text = await res.text();
  fs.writeFileSync(cacheFile, text, "utf-8");
  console.log(`Cached ${(text.length / 1024 / 1024).toFixed(2)} MB to .coe-data-cache.json`);
  return text;
}

function parse(raw) {
  // File is JS: starts with `poecd=` and may end with `;`
  const json = raw.replace(/^poecd\s*=\s*/, "").replace(/;?\s*$/, "");
  return JSON.parse(json);
}

function tsLiteral(value) {
  return JSON.stringify(value, null, 2);
}

function main() {
  getRawData().then((raw) => {
    const d = parse(raw);

    // --- Bases (item categories: "Bow", "Body Armour (INT)", "Ring") ---
    // We keyed by name_base for direct lookup; value is { b: id_base }.
    const basesByName = {};
    for (const b of d.bases.seq) {
      basesByName[b.name_base] = { b: Number(b.id_base) };
    }

    // --- Bitems (specific items: "Thicket Bow", "Sadist Garb", "Amber Amulet") ---
    // Value is { b: id_base (category), bi: id_bitem (specific) }.
    const bitemsByName = {};
    for (const bi of d.bitems.seq) {
      bitemsByName[bi.name_bitem] = {
        b: Number(bi.id_base),
        bi: Number(bi.id_bitem),
      };
    }

    // --- Essences ---
    const essencesByName = {};
    for (const e of d.essences.seq) {
      // Strip leading "Essence of " — Oracle output may say "Greater Essence of Abrasion"
      // and we want to match on "Abrasion" too.
      essencesByName[e.name_essence] = Number(e.id_essence);
      const stripped = e.name_essence.replace(/^Essence of\s+/i, "");
      if (stripped !== e.name_essence) essencesByName[stripped] = Number(e.id_essence);
    }

    const header = `// AUTO-GENERATED by scripts/build-coe-lookup.mjs — do not edit by hand.
// Source: ${DATA_URL}
// Generated: ${new Date().toISOString()}
// Bases: ${Object.keys(basesByName).length} categories, ${Object.keys(bitemsByName).length} specific items
// Essences: ${d.essences.seq.length}

/** id_base for a Craft of Exile base CATEGORY (e.g. "Bow" → 20). */
export const COE_BASE_CATEGORIES: Record<string, { b: number }> = ${tsLiteral(basesByName)};

/** id_bitem for a Craft of Exile specific item (e.g. "Crude Bow" → { b: 20, bi: 231 }).
 *  Includes the parent category id_base so URLs can fully pre-fill. */
export const COE_BITEMS: Record<string, { b: number; bi: number }> = ${tsLiteral(bitemsByName)};

/** id_essence for a Craft of Exile essence. Keyed by full name AND by stripped suffix,
 *  so both "Essence of Abrasion" and "Abrasion" resolve to the same id. */
export const COE_ESSENCES: Record<string, number> = ${tsLiteral(essencesByName)};

/** Look up the CoE base IDs for a given base name. Tries the specific-item lookup
 *  first (more precise), then falls back to the category lookup. Returns null if neither. */
export function lookupCoeBase(name: string): { b: number; bi?: number } | null {
  if (COE_BITEMS[name]) return COE_BITEMS[name];
  if (COE_BASE_CATEGORIES[name]) return COE_BASE_CATEGORIES[name];
  return null;
}

/** Look up the CoE essence ID for a name like "Essence of Abrasion" or "Abrasion"
 *  or "Greater Essence of Abrasion" (we strip the tier prefix). */
export function lookupCoeEssence(name: string): number | null {
  if (!name) return null;
  // Strip tier prefixes like "Greater ", "Perfect ", "Lesser ", "Normal "
  const stripped = name.replace(/^(Greater|Perfect|Lesser|Normal)\s+/i, "");
  return COE_ESSENCES[stripped] ?? COE_ESSENCES[name] ?? null;
}
`;

    fs.writeFileSync(outFile, header, "utf-8");
    console.log(`Wrote ${outFile}`);
    console.log(`  ${Object.keys(basesByName).length} base categories`);
    console.log(`  ${Object.keys(bitemsByName).length} specific items`);
    console.log(`  ${Object.keys(essencesByName).length} essence keys (${d.essences.seq.length} unique)`);
  });
}

main();
